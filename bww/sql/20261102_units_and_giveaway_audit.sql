-- BWW unit hierarchy and giveaway audit extensions.
-- This schema migration has already been applied to the connected Supabase project.

create table if not exists public.bww_units (
  id uuid primary key default gen_random_uuid(),
  guild_id text not null,
  unit_type text not null check (unit_type in ('kompanie','zug','gruppe')),
  parent_id uuid null references public.bww_units(id) on delete restrict,
  name text not null check (length(btrim(name)) between 1 and 100),
  responsibilities text not null default '',
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists bww_units_unique_root_name on public.bww_units (guild_id, lower(name)) where parent_id is null;
create unique index if not exists bww_units_unique_child_name on public.bww_units (guild_id, parent_id, lower(name)) where parent_id is not null;
create unique index if not exists bww_units_unique_guild_name on public.bww_units (guild_id, lower(name));
create index if not exists bww_units_guild_type_idx on public.bww_units (guild_id, unit_type, name);

create or replace function public.bww_validate_unit_parent()
returns trigger language plpgsql set search_path = public as $$
declare
  parent_type text;
  parent_guild text;
  expected_parent text;
begin
  if new.unit_type = 'kompanie' then
    if new.parent_id is not null then raise exception 'Eine Kompanie darf keine übergeordnete Einheit haben.'; end if;
    return new;
  end if;
  if new.parent_id is null then raise exception 'Ein Zug benötigt eine Kompanie; eine Gruppe benötigt einen Zug.'; end if;
  select unit_type, guild_id into parent_type, parent_guild from public.bww_units where id = new.parent_id;
  if not found then raise exception 'Übergeordnete Einheit nicht gefunden.'; end if;
  if parent_guild <> new.guild_id then raise exception 'Übergeordnete Einheit gehört zu einem anderen Server.'; end if;
  expected_parent := case new.unit_type when 'zug' then 'kompanie' when 'gruppe' then 'zug' end;
  if parent_type <> expected_parent then raise exception 'Ungültige Hierarchie: % benötigt als übergeordnete Einheit %.', new.unit_type, expected_parent; end if;
  return new;
end;
$$;
drop trigger if exists bww_units_validate_parent on public.bww_units;
create trigger bww_units_validate_parent before insert or update of unit_type, parent_id, guild_id on public.bww_units for each row execute function public.bww_validate_unit_parent();

create table if not exists public.bww_unit_members (
  id uuid primary key default gen_random_uuid(),
  guild_id text not null,
  unit_id uuid not null references public.bww_units(id) on delete cascade,
  user_id text not null,
  position text not null default 'mitglied' check (position in ('mitglied','leiter','stellvertreter')),
  assigned_by text,
  assigned_at timestamptz not null default now(),
  unique (unit_id, user_id)
);
create index if not exists bww_unit_members_guild_user_idx on public.bww_unit_members (guild_id, user_id);
create index if not exists bww_unit_members_unit_idx on public.bww_unit_members (unit_id, position, assigned_at);
create unique index if not exists bww_unit_one_leader on public.bww_unit_members (unit_id) where position = 'leiter';
create unique index if not exists bww_unit_one_deputy on public.bww_unit_members (unit_id) where position = 'stellvertreter';

